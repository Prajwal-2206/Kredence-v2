// Simple deterministic hash function for mock data consistency
function djb2Hash(str: string): number {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) + hash) + str.charCodeAt(i); 
  }
  return Math.abs(hash);
}

export function getDeterministicIdentity(address: string) {
  const hash = djb2Hash(address.toLowerCase());
  
  // Seed derivations
  const lensFollowers = 100 + (hash % 10000);
  const farcasterId = hash % 20000;
  const trustScore = 70 + (hash % 30);
  
  let sybilGrade = "C";
  if (trustScore > 95) sybilGrade = "A+";
  else if (trustScore > 90) sybilGrade = "A";
  else if (trustScore > 80) sybilGrade = "B";

  // Assign deterministic badges
  const badges = [];
  const assignedIndexes = new Set<number>();
  
  // They always get 4-8 badges
  const numBadges = 4 + (hash % 5);
  for (let i = 0; i < numBadges; i++) {
    const nextIdx = (hash + i * 17) % ACHIVEMENTS_DB.length;
    if (!assignedIndexes.has(nextIdx)) {
      badges.push(ACHIVEMENTS_DB[nextIdx]);
      assignedIndexes.add(nextIdx);
    }
  }

  // Radar chart deterministic axes
  // [Wallet Age, CEX Funding, Tx Randomness, Governance Voting, Liquidity Provision]
  // In percentiles (0-100)
  const radarData = [
    { subject: 'Wallet Age', A: 20 + (hash % 80), fullMark: 100 },
    { subject: 'CEX Funding', A: 40 + ((hash * 2) % 60), fullMark: 100 },
    { subject: 'Tx Randomness', A: 30 + ((hash * 3) % 70), fullMark: 100 },
    { subject: 'Gov Voting', A: (hash % 100), fullMark: 100 },
    { subject: 'Liquidity', A: 10 + ((hash * 7) % 90), fullMark: 100 },
  ];

  return {
    lensFollowers: (lensFollowers / 1000).toFixed(1) + 'k',
    farcasterId: `#${farcasterId}`,
    trustScore: trustScore.toFixed(1),
    sybilGrade,
    badges,
    radarData
  };
}
